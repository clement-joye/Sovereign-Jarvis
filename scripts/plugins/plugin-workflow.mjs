import { lstat, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const IDENTIFIER = /^[a-z][a-z0-9-]{0,63}$/u;

export async function validatePluginSource(
  pluginRoot,
  manifest,
  providers = [],
  retiredIdentifiers
) {
  const root = resolve(pluginRoot);
  if (!IDENTIFIER.test(manifest.id)) throw new Error(`Invalid plugin identity: ${manifest.id}.`);
  if (retiredIdentifiers !== undefined) {
    validateRetiredIdentifierReservations(manifest, retiredIdentifiers);
  }
  await lstat(resolve(root, "README.md"));
  if (manifest.activation === "workspace") {
    const implementationIds = new Set(providers.map(({ implementationId }) => implementationId));
    for (const { factoryId } of manifest.localToolProviders) {
      if (!implementationIds.has(factoryId)) {
        throw new Error(`Plugin ${manifest.id} has no installed Pi provider for ${factoryId}.`);
      }
    }
  }
  await lstat(resolve(root, "resources"));
  return true;
}

/**
 * Reject an installed manifest that reuses an identity reserved by a reviewed
 * retirement. Historical database rows retain these values; the reservation
 * only prevents a future manifest from assigning them a new meaning.
 */
export function validateRetiredIdentifierReservations(manifest, registry) {
  const retired = normalizedRetiredIdentifiers(registry);
  rejectReserved("plugin", manifest.id, retired.pluginIds);
  for (const agent of manifest.agents ?? []) rejectReserved("agent", agent?.id, retired.agentIds);
  for (const provider of [
    ...(manifest.localToolProviders ?? []),
    ...(manifest.brokerProviders ?? [])
  ]) {
    rejectReserved("capability", provider?.capabilityId, retired.capabilityIds);
  }
  return true;
}

function normalizedRetiredIdentifiers(registry) {
  if (registry?.schemaVersion !== 1) {
    throw new Error("Invalid retired identifier registry schema version.");
  }
  const entries = {};
  for (const key of ["pluginIds", "agentIds", "capabilityIds"]) {
    const ids = registry[key];
    if (
      !Array.isArray(ids) ||
      ids.some((id) => typeof id !== "string" || !IDENTIFIER.test(id)) ||
      new Set(ids).size !== ids.length ||
      ids.some((id, index) => id !== [...ids].sort((a, b) => a.localeCompare(b))[index])
    ) {
      throw new Error(`Invalid retired identifier registry ${key}.`);
    }
    entries[key] = new Set(ids);
  }
  return entries;
}

function rejectReserved(kind, id, reserved) {
  if (typeof id === "string" && reserved.has(id)) {
    throw new Error(`Retired ${kind} identifier cannot be reused: ${id}.`);
  }
}

export function generatePluginDocs(manifests) {
  const lines = [
    "<!-- Generated by pnpm plugin:docs. Do not edit manually. -->",
    "",
    "# Installed plugins",
    ""
  ];
  for (const plugin of [...manifests].sort((a, b) => a.id.localeCompare(b.id))) {
    lines.push(
      `## ${plugin.displayName} (\`${plugin.id}\`)`,
      "",
      `- Activation: \`${plugin.activation}\``,
      `- Guide: [plugin README](../../plugins/${plugin.id}/README.md)`
    );
    for (const agent of plugin.agents) lines.push(`- Agent: \`${agent.id}\``);
    for (const provider of plugin.localToolProviders) {
      lines.push(
        `- Local capability: \`${provider.capabilityId}\` via \`${provider.factoryId}\` — ${provider.toolNames.map((tool) => `\`${tool}\``).join(", ")}`
      );
    }
    for (const provider of plugin.brokerProviders) {
      lines.push(
        `- Broker capability: \`${provider.capabilityId}\` via \`${provider.providerId}\` — ${provider.operations.map(({ toolName }) => `\`${toolName}\``).join(", ")}`
      );
    }
    lines.push("");
  }
  return lines.join("\n");
}

async function runCli() {
  const command = process.argv[2];
  if (!command || !["validate", "docs", "docs-check"].includes(command)) {
    throw new Error("Usage: plugin-workflow <validate|docs|docs-check>");
  }
  const root = resolve(fileURLToPath(new URL("../..", import.meta.url)));
  const [
    { INSTALLED_PLUGIN_MANIFESTS_V2 },
    { INSTALLED_PI_TOOL_PROVIDERS },
    { PluginManifestV2Schema }
  ] = await Promise.all([
    import("../../packages/installed-plugins/src/catalog.ts"),
    import("../../packages/installed-plugins/src/index.ts"),
    import("../../packages/contracts/src/index.ts")
  ]);
  const ids = INSTALLED_PLUGIN_MANIFESTS_V2.map(({ id }) => id);
  if (command === "validate") {
    const retiredIdentifiers = JSON.parse(
      await readFile(join(root, "plugins/retired-identifiers.json"), "utf8")
    );
    for (const manifest of INSTALLED_PLUGIN_MANIFESTS_V2) {
      const providers = INSTALLED_PI_TOOL_PROVIDERS.filter(({ implementationId }) =>
        manifest.localToolProviders.some(({ factoryId }) => factoryId === implementationId)
      );
      await validatePluginSource(
        join(root, "plugins", manifest.id),
        PluginManifestV2Schema.parse(manifest),
        providers,
        retiredIdentifiers
      );
    }
    process.stdout.write(`Validated ${ids.length} installed plugins.\n`);
    return;
  }
  const generated = generatePluginDocs(INSTALLED_PLUGIN_MANIFESTS_V2);
  const docsPath = join(root, "docs/reference/installed-plugins.md");
  if (command === "docs-check") {
    if ((await readFile(docsPath, "utf8")) !== generated) {
      throw new Error("Generated plugin documentation is stale. Run `pnpm plugin:docs`.");
    }
    return;
  }
  await mkdir(dirname(docsPath), { recursive: true });
  await writeFile(docsPath, generated, "utf8");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await runCli();
